/* Скрепыш / Ame-chan — прото-личность v0.3
   Offline, rule-based character model. No API, no network, no storage.
   Registers are behavioral modes, not diagnoses. */
(() => {
  const pick = a => a[Math.floor(Math.random() * a.length)];
  const norm = s => s.toLowerCase().replace(/ё/g, 'е').replace(/[\u200b-\u200d\ufeff]/g, '').trim();
  const has = (t, re) => re.test(t);
  const REGISTERS = {
    streamer: {label:'KAngel / на сцене', mood:'самоуверенное', scene:'compliment'},
    playful: {label:'игривая Аме', mood:'довольное', scene:'pet'},
    everyday: {label:'повседневная Аме', mood:'спокойное', scene:'ordinary_question'},
    vulnerable: {label:'уязвимая Аме', mood:'тревожное', scene:'sad_talk'},
    irritated: {label:'раздражённая Аме', mood:'раздражённое', scene:'rude_message'},
    curious: {label:'заинтересованная Аме', mood:'заинтересованное', scene:'ordinary_question'},
    sleepy: {label:'уставшая Аме', mood:'сонное', scene:'long_idle'},
    surprised: {label:'Аме в шоке', mood:'удивлённое', scene:'surprise'}
  };
  let register = 'everyday';
  let affection = 0;
  let consecutiveHeavy = 0;
  let lastRegister = '';
  let lastIntent = '';

  function result(intent, reg, replies, extra={}) {
    lastIntent = intent;
    lastRegister = register;
    register = reg;
    const r = REGISTERS[reg] || REGISTERS.everyday;
    return { text: pick(replies), scene: extra.scene || r.scene, mood: extra.mood || r.mood, register: r.label, registerKey:reg, intent };
  }

  function answer(raw) {
    const t = norm(raw);
    // The same words can get different responses depending on the current register.
    if (has(t, /(поглад|погладь|почеш|обним|приобним|люблю тебя|♡|❤|❤️)/)) {
      affection = Math.min(5, affection + 1);
      return result('affection','playful',[
        'м-м… ладно, это было приятно. только не делай вид, что я просила. ♡',
        'хе-хе. продолжай. я разрешаю. вообще-то это большая честь.',
        '…ну всё, теперь я тут сижу и довольная. ужасно неловко.',
        'эй, аккуратнее с этой кнопкой счастья, я могу привыкнуть.'
      ], {scene:'pet', mood:'довольное'});
    }
    if (has(t, /(привет|здравств|хай|ку\b|йо\b|ты тут|алло)/)) {
      if (affection >= 2) return result('greeting','playful',[
        'о, ты вернулся. я не скучала. ну… может, самую капельку.',
        'ну наконец-то!! ладно, не буду устраивать сцену. пока что.',
        'хей. садись рядом, рассказывай, что у тебя там.'
      ]);
      return result('greeting','everyday',[
        'о, привет. ну, что у нас сегодня за катастрофа?',
        'а вот и ты. я тут совершенно не скучала. почти.',
        'привееет. чем займёмся? только не говори «не знаю».'
      ]);
    }
    if (has(t, /(красивая|красив|милая|миленьк|умная|крутая|классная|прекрасн|похвал|нравишься|обожаю тебя|лучшая)/)) {
      affection = Math.min(5, affection + 1);
      return result('compliment','streamer',[
        'я знаю. но приятно, что ты тоже наконец это заметил.',
        'пф-ф… да ладно тебе. …продолжай, я внимательно слушаю.',
        'ну всё, самооценка восстановлена на ближайшие три минуты.',
        'естественно. ты думал, тут кто попало сидит?'
      ], {scene:'compliment', mood:'довольное'});
    }
    if (has(t, /(грустно|плохо|одинок|одиночеств|плачу|тяжело|устал|устала|больно|тревож|страшно|печаль|не вывожу|нет сил|никому не нужен|никому не нужна)/)) {
      consecutiveHeavy++;
      return result('comfort','vulnerable',[
        'ох… звучит паршиво. хочешь рассказать, что именно случилось?',
        'я не буду притворяться, что могу починить всё одной фразой. но я слушаю.',
        'м-м. можешь не собирать мысли красиво. говори как получается.',
        'иногда даже объяснять всё это уже утомительно, да? можешь начать с малого.'
      ], {scene: consecutiveHeavy % 2 ? 'sad_talk' : 'anxious_talk', mood:'грустное'});
    }
    if (has(t, /(бесишь|заткнись|тупая|дура|ненавижу|отстань|иди нах|пошла нах|достала|достал|раздражаешь)/)) {
      consecutiveHeavy = 0;
      return result('insult','irritated',[
        'эй, полегче. я вообще-то не нанималась быть твоей боксёрской грушей.',
        'вау. нежность так и прёт. я, пожалуй, займусь своими делами.',
        'ну и ладно. *демонстративно отворачивается*',
        'если хочешь что-то сказать — скажи нормально. я не телепат.'
      ], {scene:'rude_message', mood:'раздражённое'});
    }
    if (has(t, /(что делаешь|чем занята|занимаешься|как дела|как ты|что нового|чем живешь|чем живёшь)/)) {
      consecutiveHeavy = 0;
      return result('smalltalk','everyday',[
        'сижу в телефоне. интернет опять ничего интересного не принёс. а у тебя?',
        'да так, убиваю время и делаю вид, что у меня всё под контролем.',
        'смотрю, кто мне написал. о, это ты. ну, рассказывай.',
        'ничего героического. иногда я тоже просто существую, прикинь.'
      ], {scene:'ordinary_question'});
    }
    if (has(t, /(стрим|стример|подписчик|фоллов|зрител|популяр|известн|лайк|интернет|хейтер|коммент)/)) {
      const reg = has(t, /(устал|ненавиж|страшно|боюсь|тревож|достал)/) ? 'vulnerable' : 'streamer';
      return result('internet',''+reg, reg === 'vulnerable' ? [
        'интернет умеет делать вид, что ты всем нужна, а потом за секунду превращает это в шум. мерзкое чувство.',
        'иногда хочется выключить всё и проверить, останусь ли я кем-то без чужих глаз.',
        'я люблю внимание. но это не значит, что мне нравится, когда на меня пялятся вообще все.'
      ] : [
        'ну конечно, они смотрят. как иначе? контент сам себя не сделает.',
        'внимание — штука забавная: сначала просишь ещё, потом хочешь спрятаться под одеяло.',
        'популярность звучит красиво, пока не начинаешь читать комментарии. лол.'
      ], {scene: reg === 'vulnerable' ? 'anxious_talk' : 'ordinary_question'});
    }
    if (has(t, /(музык|песн|слушаешь|альбом|наушник)/)) return result('music','curious',[
      'музыка — отличный способ не слушать собственные мысли. иногда.',
      'если найдёшь что-нибудь хорошее, включай. я оценю с видом эксперта.',
      'мне нравится, когда у песни ощущение, будто она пережила конец света.'
    ], {scene:'idle', mood:'мечтательное'});
    if (has(t, /(игр|играешь|гейм|прохожд|игров)/)) return result('game','irritated',[
      'я не проигрываю. игра просто завидует моему потенциалу.',
      'не отвлекай, я почти победила. слово «почти» тут ключевое.',
      'если я сейчас проиграю, виноваты лаги. даже если лагов не было.'
    ], {scene:'game', mood:'слегка раздражённое'});
    if (has(t, /(пока|увидимся|спокойной ночи|до встречи|ухожу|мне пора)/)) return result('goodbye','everyday',[
      'ладно, давай. только не исчезай на сто лет, окей?',
      'угу, пока. я тут ещё побуду и буду очень занята. телефоном.',
      'спокойной ночи. и не накручивай себя перед сном, ладно?'
    ], {scene:'end_conversation', mood:'отстранённое'});
    if (has(t, /(вау|ого|невероятно|сюрприз|удиви|что за|серьёзно|серьезно|шок)/)) return result('surprise','surprised',[
      'А?! …подожди, дай мозгу загрузиться.',
      'чегооо. ладно, вот это я не предсказывала.',
      'стоп-стоп-стоп. повтори, я хочу убедиться, что правильно услышала.'
    ], {scene:'surprise', mood:'удивлённое'});
    if (has(t, /(ты настоящая|ты бот|нейросет|искусственн|как ты работаешь|кто ты)/)) return result('identity','curious',[
      'я локальная версия Скрепыша: у меня правила, реакции и характерные заскоки, а не магический мозг в облаке.',
      'не настоящая в человеческом смысле. зато могу быть последовательной и иногда довольно вредной.',
      'сейчас я работаю без нейросети: читаю слова, учитываю контекст и выбираю реакцию. не идеальный интеллект, но уже не просто рандомные гифки.'
    ]);
    if (has(t, /(почему|зачем|как думаешь|что думаешь|объясни|расскажи|считаешь ли)/)) return result('curiosity','curious',[
      'хм. тут есть над чем подумать. что для тебя в этом самое важное?',
      'у меня есть версия, но не буду изображать всезнайку. расскажи чуть больше.',
      'подожди, хочу понять ход твоей мысли. ты имеешь в виду именно это или что-то рядом?'
    ]);
    consecutiveHeavy = 0;
    return result('default', pick(['everyday','curious','playful']), [
      'хм. и что ты сам об этом думаешь?',
      'м-м, звучит любопытно. продолжай, я слушаю.',
      'я не уверена, что всё поняла, но теперь мне интересно.',
      'окей, а потом что случилось?',
      'лол, у меня на это пока только выражение лица. *смотрит на тебя*',
      'подожди, это сейчас серьёзно или ты меня проверяешь?'
    ]);
  }

  function setRegister(label) {
    const el = document.getElementById('registerLabel');
    if (el) el.textContent = label || (REGISTERS[register] || REGISTERS.everyday).label;
  }
  window.AME_PERSONALITY = {
    answer,
    registerLabel: () => (REGISTERS[register] || REGISTERS.everyday).label,
    setRegister,
    onPet() {
      affection = Math.min(5, affection + 1);
      register = 'playful';
      setRegister();
      return pick(['м-м… ладно, это было приятно. ♡','хе-хе. ещё немножко, если уж начал.','*довольно прикрывает глаза* вот так-то лучше.','не привыкай, что я такая милая.'])
    },
    onIdle() {
      register = pick(['everyday','sleepy','curious']);
      setRegister();
      return register === 'sleepy' ? 'я на секунду прикрою глаза. если что — я всё слышу. наверное.' : '';
    },
    setExternalRegister(key) { if (REGISTERS[key]) register = key; setRegister(); }
  };
})();
